import argparse
import getpass
import json
import sys
from pathlib import Path

import httpx

from .client import TelekomClient, TelekomError
from .usage import parse_consumption
from .web import TelekomWebClient, parse_data_balances


def main():
    parser = argparse.ArgumentParser(description='Experimental Telekom HU mobile HTTP client')
    parser.add_argument('--session', type=Path, default=Path('.telekom/session.json'))
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('nonce', help='Create an attestation nonce (live verified)')
    login = sub.add_parser('login', help='Experimental phone/SMS flow; currently blocked by HTTP 417')
    login.add_argument('phone')
    login.add_argument('--attestation', type=Path,
                       help='Local JSON with nonce and legitimate statement; not generated by this tool')
    sub.add_parser('verify', help='Enter SMS code privately (experimental)')
    profiles = sub.add_parser('profiles')
    profiles.add_argument('subject', help='Token subject, as returned by Telekom')
    dashboard = sub.add_parser('dashboard')
    dashboard.add_argument('profile_id')
    usage = sub.add_parser('usage')
    usage.add_argument('profile_id')
    usage.add_argument('product_id')
    usage.add_argument('--raw', action='store_true')
    extra = sub.add_parser('extra-data')
    extra.add_argument('profile_id')
    sub.add_parser('refresh')
    parse = sub.add_parser('parse-usage', help='Parse a saved dashboard consumption response offline')
    parse.add_argument('file', type=Path)
    for name in ('web-profile', 'web-assets', 'web-usage'):
        command = sub.add_parser(name, help='Read the web API using an exported browser session')
        command.add_argument('--web-session', type=Path, default=Path('.telekom/web-session.json'))
        if name == 'web-usage':
            command.add_argument('product_id', nargs='?')
            command.add_argument('--phone', help='Look up your subscription by phone number')
            command.add_argument('--raw', action='store_true')
    args = parser.parse_args()
    try:
        if args.command == 'parse-usage':
            allowance = parse_consumption(json.loads(args.file.read_text()))
            print(json.dumps(allowance.to_dict() if allowance else None, indent=2))
            return
        if args.command.startswith('web-'):
            with TelekomWebClient.load(args.web_session) as web:
                if args.command == 'web-profile':
                    result = web.profile()
                elif args.command == 'web-assets':
                    result = web.assets()
                else:
                    if bool(args.phone) == bool(args.product_id):
                        raise ValueError('Supply either --phone NUMBER or a product identifier')
                    if args.phone:
                        result = web.usage_for_phone(args.phone, raw=args.raw)
                    else:
                        raw = web.data_balances(args.product_id)
                        result = raw if args.raw else {'allowances': parse_data_balances(raw)}
                print(json.dumps(result, indent=2, ensure_ascii=False))
            return
        client = TelekomClient.load(args.session) if args.session.exists() else TelekomClient()
        with client:
            match args.command:
                case 'nonce':
                    result = client.create_attestation_nonce()
                case 'login':
                    print('Experimental: live SMS login is not yet verified; current server response is HTTP 417.',
                          file=sys.stderr)
                    attestation = json.loads(args.attestation.read_text()) if args.attestation else {}
                    result = client.request_sms(args.phone, attestation_nonce=attestation.get('nonce'),
                                                attestation_statement=attestation.get('statement'))
                    # Avoid logging nonce or other server account metadata.
                    result = {'sms_requested': True}
                case 'verify':
                    client.verify_sms(getpass.getpass('SMS code: '))
                    result = {'authenticated': True}
                case 'profiles':
                    result = client.profiles(args.subject)
                case 'dashboard':
                    result = client.dashboard(args.profile_id)
                case 'usage':
                    raw = client.usage_raw(args.product_id, args.profile_id)
                    allowance = None if args.raw else parse_consumption(raw)
                    result = raw if args.raw else allowance.to_dict() if allowance else None
                case 'extra-data':
                    result = client.extra_data(args.profile_id)
                case 'refresh':
                    client.refresh()
                    result = {'refreshed': True}
            client.save(args.session)
            print(json.dumps(result, indent=2, ensure_ascii=False))
    except (TelekomError, httpx.HTTPError, ValueError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from None


if __name__ == '__main__':
    main()
